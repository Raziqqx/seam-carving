// test_support.hpp - helpers shared by the test files: random inputs and brute force.
#pragma once

#include <random>

#include "seam/types.hpp"

namespace test_support {

// The project is merged milestone by milestone. Until a milestone is merged, its functions
// are placeholders that throw seam::NotImplementedYet. A test that needs such a function
// calls the matching require_...() first: it tries the function once and, if it is still a
// placeholder, SKIPS the test (Catch2 reports it as skipped, not failed).
void require_greedy();            // milestone 2: greedy seam finder
void require_graphcut();          // milestone 3: max-flow and graph-cut seam finder
void require_all_seam_finders();  // greedy and graph cut (DP is always there)

// Random energy grid with values in [0, max_value]. The same seed gives the same grid,
// so a failing test can be reproduced.
seam::EnergyMap random_energy(int rows, int cols, int max_value, unsigned seed);

// Random 8-bit gray image.
cv::Mat_<uchar> random_gray(int rows, int cols, unsigned seed);

// Random 8-bit BGR colour image.
cv::Mat random_colour(int rows, int cols, unsigned seed);

// Builds an energy map from a list of rows, e.g. make_energy({{1, 2}, {3, 4}}).
seam::EnergyMap make_energy(const std::vector<std::vector<int>>& rows);

// Every valid vertical seam of a rows x cols image, generated by trying all moves.
// The number of seams is exponential in `rows`, so only call this for tiny sizes.
std::vector<seam::Seam> all_seams(int rows, int cols);

// Smallest seam cost over ALL seams (exhaustive search).
long long brute_force_min_cost(const seam::EnergyMap& energy);

}  // namespace test_support
